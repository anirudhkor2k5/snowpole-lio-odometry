"""Run the snow-pole pipeline (snowpole_stage3.py) for every odometry input x stage-3 mode, then write
results/pipeline/PIPELINE_RESULTS.md and figures. New file; nothing in the original repo is modified.

  python lio_bench/pipeline/run_all_variants.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402

sys.path.insert(0, str(Path(__file__).resolve().parent))
import snowpole_stage3 as S  # noqa: E402

EXP = S.REPO / "lio_bench" / "results" / "export"
INPUTS = [  # (label, csv, description)
    ("fastlio_raw", EXP / "incremental_navigation_fast_lio_full_raw.csv", "FAST-LIO2 raw (baseline)"),
    ("fasterlio_raw", EXP / "incremental_navigation_faster_lio_full_raw.csv", "Faster-LIO raw"),
    ("fastlio_g", EXP / "incremental_navigation_fast_lio_full_gravity.csv", "FAST-LIO2 + gravity"),
    ("fasterlio_g", EXP / "incremental_navigation_faster_lio_full_gravity.csv", "Faster-LIO + gravity"),
    ("fastlio_gk", EXP / "incremental_navigation_fast_lio_full_gravity_kiss_heading.csv", "FAST-LIO2 + gravity + KISS heading"),
    ("fasterlio_gk", EXP / "incremental_navigation_faster_lio_full_gravity_kiss_heading.csv", "Faster-LIO + gravity + KISS heading (offline)"),
    ("final_online", EXP / "incremental_navigation_kiss_fusion_rt_fusion_v20_run.csv", "**Final: online node (Faster-LIO + gravity + KISS[2 m] heading)**"),
    ("legacy_csv", S.REPO / "incremental_navigation_results.csv", "legacy incremental_navigation_results.csv (reference only, not a baseline)"),
]
MODES = [("none", "original pipeline (position reset at poles)"), ("reset", "+ heading reset at poles"),
         ("reset+rate", "+ heading reset + drift rate")]
OUT = S.OUT


def main():
    rows = []
    for lab, csv, desc in INPUTS:
        for mode, mdesc in MODES:
            name = f"{lab}__{mode.replace('+', '_')}"
            print(f"[run] {name}", flush=True)
            r = S.run(str(csv), mode, name)
            rows.append((lab, desc, mode, mdesc, r))
    (OUT / "all_results.json").write_text(json.dumps([r for *_, r in rows], indent=2))
    write_md(rows)
    figures(rows)


def f(x, nd=1):
    return "—" if x is None or (isinstance(x, float) and not np.isfinite(x)) else f"{x:.{nd}f}"


def write_md(rows):
    r0 = rows[0][4]
    L = ["# Snow-pole pipeline with the new odometry: results\n",
         "*Generated by `lio_bench/pipeline/run_all_variants.py`. The localisation loop is a step-for-step "
         "re-implementation of `snowpole_based_vehicle_localization.py` (original untouched) using the repo's "
         "`geoloc_utils` functions and YOLO model; detections cached once (`detections_cache.pkl`). Error = "
         "distance between the pipeline's predicted vehicle position and the dual-GNSS midpoint kriged to the "
         "range-image stamps (the original's reference).*\n",
         f"- **Whole drive:** {r0['whole_drive']['length_km']:.1f} km, {r0['whole_drive']['n']} frames.",
         f"- **Pole span:** reference track from the first to the last surveyed pole: km "
         f"{r0['pole_span']['from_km']:.2f} → {r0['pole_span']['to_km']:.2f} ({r0['pole_span']['n']} frames).",
         "- **Native metric:** the original pipeline's own number (frames whose *predicted* position is inside "
         "the pole map's bounding box).\n"]
    for title, key, cols in (
            ("1. Whole drive (10.3 km)", "whole_drive", [("mean", "mean m"), ("median", "median m"), ("p95", "p95 m"), ("final_m", "final m")]),
            ("2. First pole → last pole", "pole_span", [("mean", "mean m"), ("median", "median m"), ("p95", "p95 m"), ("max", "max m"), ("at_exit_m", "at last pole m")]),
            ("3. After the last pole (no poles)", "after_last_pole", [("mean", "mean m"), ("median", "median m"), ("final_m", "final m")]),
            ("4. Native pipeline metric (bounding box)", "native_box_metric", [("mean", "mean m"), ("median", "median m"), ("n", "frames")])):
        L.append(f"\n## {title}\n")
        L.append("| odometry input | stage 3 | " + " | ".join(c[1] for c in cols) + " | pole fixes | heading updates |")
        L.append("|---|---|" + "---:|" * (len(cols) + 2))
        for lab, desc, mode, mdesc, r in rows:
            v = r[key]
            L.append(f"| {desc} | {mdesc} | " + " | ".join(f(v.get(c[0]), 0 if c[0] == "n" else 1) for c in cols)
                     + f" | {r['pole_fixes']} | {r['heading_updates']} |")
    (OUT / "PIPELINE_RESULTS.md").write_text("\n".join(L) + "\n")
    print("wrote", OUT / "PIPELINE_RESULTS.md")


def figures(rows):
    C = {"fastlio_raw": "#eb6834", "fasterlio_raw": "#2a78d6", "fasterlio_gk": "#1baf7a", "final_online": "#6250d6"}
    LAB = {"fastlio_raw": "FAST-LIO2 raw (baseline)", "fasterlio_raw": "Faster-LIO raw",
           "fasterlio_gk": "Faster-LIO + gravity + KISS (offline)", "final_online": "final online node"}
    plt.rcParams.update({"font.size": 9, "axes.spines.top": False, "axes.spines.right": False,
                         "axes.grid": True, "grid.color": "#e4e3df"})
    for mode, mdesc in MODES:
        fig, ax = plt.subplots(figsize=(7.5, 3.6))
        for lab in C:
            d = pd.read_csv(OUT / f"{lab}__{mode.replace('+', '_')}_frames.csv")
            ax.plot(d["s_km"], d["err_m"], color=C[lab], lw=1.4, label=LAB[lab])
        r0 = rows[0][4]["pole_span"]
        ax.axvspan(r0["from_km"], r0["to_km"], color="#eeeeea", zorder=0, label="poles (first → last)")
        ax.set_yscale("log")
        ax.set_xlabel("distance along the drive [km]")
        ax.set_ylabel("position error [m] (log)")
        ax.set_title(f"Pipeline position error — {mdesc}", loc="left", fontsize=10)
        ax.legend(fontsize=8, loc="upper left")
        fig.tight_layout()
        fig.savefig(OUT / f"error_vs_distance__{mode.replace('+', '_')}.png", dpi=170)
        plt.close(fig)


if __name__ == "__main__":
    main()
